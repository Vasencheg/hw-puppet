"""Charger bench package: LTC4162-L, PCA9536 and LM75B over one I2C bus.

Runs inside the MicroPython VM on the ESP32-S3 HW Puppet board, resident in
/lib/pb. The host drives it over the CDC 0 Raw REPL (host/pbtest.py) or
through the ae-hw-bridge MCP `exec` tool:

    import pb; pb.init(); print(pb.snapshot_json())
"""

import json

from . import btnpwr, i2cbus, lm75b, ltc4162, pca9536

VERSION = "1.0.0"

_notes = []


def stamp():
    """Fingerprint of the sources this package was uploaded from, or None.

    `_stamp.py` is generated by the uploader, so a package copied by hand
    simply reports None and the caller re-deploys."""
    try:
        from ._stamp import STAMP

        return STAMP
    except ImportError:
        return None


def _note(msg):
    if msg:
        _notes.append(msg)


def init(start_button=True, hold_time_ms=btnpwr.DEFAULT_HOLD_MS):
    """Bring up the bus and all three devices.

    The custom adaptive JEITA curve is deliberately NOT applied here: the
    charger runs on its own reset values so that hardware charging behaviour
    can be observed as-is. Use jeita_custom() to load it.
    """
    i2cbus.init()
    result = {"i2c": True, "lm75b": False, "pca9536": False, "ltc4162": False}
    for name, fn in (("lm75b", lm75b.init), ("pca9536", pca9536.init), ("ltc4162", ltc4162.init)):
        try:
            fn()
            result[name] = True
        except OSError as err:
            result[name] = str(err)
    if start_button:
        btnpwr.start(hold_time_ms)
    result["button_watcher"] = btnpwr.is_running()
    result["version"] = VERSION
    return result


def _safe(fn, *args):
    """Call a telemetry getter, returning None when the device does not answer."""
    try:
        return fn(*args)
    except OSError:
        return None


def snapshot():
    """One full reading of the board. Values that could not be read are None,
    so the host can print a dash instead of a number that looks measured."""
    try:
        _note(ltc4162.ensure_configured())
        ltc_alive = True
    except OSError:
        ltc_alive = False

    raw_io = _safe(pca9536.read_raw)
    if raw_io is None:
        btn = sim = None
    else:
        btn = (raw_io & pca9536.PIN_EXT_BTN) == 0
        sim = (raw_io & pca9536.PIN_SIM_ON) == 0

    snap = {
        "t_brd": _safe(lm75b.read_temp),
        "raw_io": raw_io,
        "btn": btn,
        "sim": sim,
        "led": pca9536.led_pwr_state(),
        "btn_pressed": btnpwr.is_pressed(),
        "btn_hold_s": btnpwr.hold_sec(),
        "hold_time_ms": btnpwr.get_hold_time(),
        "ltc_alive": ltc_alive,
        "events": btnpwr.take_events() + _drain_notes(),
    }

    if ltc_alive:
        snap.update(
            {
                "vin": _safe(ltc4162.get_vin),
                "vout": _safe(ltc4162.get_vout),
                "vbat": _safe(ltc4162.get_vbat),
                "ibat": _safe(ltc4162.get_ibat),
                "iin": _safe(ltc4162.get_iin),
                "ilim": _safe(ltc4162.ilim_get),
                "t_die": _safe(ltc4162.get_die_temp),
                "chg_state": _safe(ltc4162.get_charger_state),
                "chg_status": _safe(ltc4162.get_charge_status),
                "sys_status": _safe(ltc4162.get_system_status),
                "ship_armed": _safe(ltc4162.is_ship_mode_armed),
                "jeita": _safe(ltc4162.jeita_is_enabled),
            }
        )
    else:
        for key in (
            "vin", "vout", "vbat", "ibat", "iin", "ilim", "t_die",
            "chg_state", "chg_status", "sys_status", "ship_armed", "jeita",
        ):
            snap[key] = None

    return snap


def _drain_notes():
    global _notes
    out = _notes
    _notes = []
    return out


def snapshot_json():
    return json.dumps(snapshot())


def stage_short():
    """Seven-character charger stage tag for the monitor line."""
    state = _safe(ltc4162.get_charger_state)
    return "  ---  " if state is None else ltc4162.charger_state_short(state)


def selftest():
    """Run the full suite and return (all_passed, lines)."""
    lines = [
        "**************************************************",
        "*        STARTING CHARGER BENCH SELF-TEST        *",
        "**************************************************",
    ]
    bus_ok, bus_lines = i2cbus.self_test()
    lines += bus_lines

    lm_ok, temp, lm_lines = lm75b.self_test()
    lines += lm_lines
    pca_ok, pca_lines = pca9536.self_test()
    lines += pca_lines
    ltc_ok, ltc_lines = ltc4162.self_test()
    lines += ltc_lines

    lines += [
        "**************************************************",
        "*               SELF-TEST SUMMARY                *",
        "**************************************************",
        "  1. I2C Bus Devices Discovery : [%s]" % (" PASS " if bus_ok else "!FAIL!"),
        "  2. LM75B Temp Sensor (0x49)  : [%s] (Temp: %s)"
        % (" PASS " if lm_ok else "!FAIL!", "%.2f C" % temp if temp is not None else "n/a"),
        "  3. PCA9536 GPIO Exp (0x41)   : [%s]" % (" PASS " if pca_ok else "!FAIL!"),
        "  4. LTC4162 Charger (0x68)    : [%s]" % (" PASS " if ltc_ok else "!FAIL!"),
        "**************************************************",
    ]
    all_ok = bus_ok and lm_ok and pca_ok and ltc_ok
    lines.append(
        ">>> ALL I2C HARDWARE TESTS PASSED SUCCESSFULLY! <<<"
        if all_ok
        else ">>> WARNING: ONE OR MORE HARDWARE TESTS FAILED! <<<"
    )
    return all_ok, lines


def selftest_json():
    ok, lines = selftest()
    return json.dumps({"ok": ok, "lines": lines})


def scan_json():
    ok, lines = i2cbus.self_test()
    return json.dumps({"ok": ok, "lines": lines})


# ---------------------------------------------------------------------------
# Thin wrappers so the host (and an MCP agent) can drive the board with
# one-liners instead of reaching into the submodules.
# ---------------------------------------------------------------------------


def led(on):
    pca9536.set_led_pwr(on)
    return pca9536.led_pwr_state()


def ship():
    """Arm Ship Mode. Returns the VIN reading taken just before arming."""
    vin = _safe(ltc4162.get_vin)
    ltc4162.arm_ship_mode()
    return vin


def disarm():
    return ltc4162.disarm_ship_mode()


def hold(ms=None):
    if ms is not None:
        btnpwr.set_hold_time(ms)
    return btnpwr.get_hold_time()


def jeita_state():
    r27 = ltc4162.read_reg(ltc4162.REG_ICHARGE_JEITA_6_5)
    r28 = ltc4162.read_reg(ltc4162.REG_ICHARGE_JEITA_4_3_2)
    r29 = ltc4162.read_reg(ltc4162.REG_CHARGER_CONFIG)
    return {
        "enabled": (r29 & ltc4162.CC_EN_JEITA) != 0,
        "c_over_x_term": (r29 & ltc4162.CC_EN_C_OVER_X_TERM) != 0,
        "r27": r27,
        "r28": r28,
        "r29": r29,
        "r27_stock": r27 == ltc4162.ICHARGE_JEITA_6_5_RESET,
        "r28_stock": r28 == ltc4162.ICHARGE_JEITA_4_3_2_RESET,
    }


def jeita_state_json():
    return json.dumps(jeita_state())


def jeita_custom(amps=1.5):
    ltc4162.set_adaptive_jeita(amps)
    ltc4162.jeita_enable(True)
    return amps
